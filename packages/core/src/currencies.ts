export interface CurrencyInfo {
  code: string;
  decimals: number;
  symbol: string;
  name: string;
}

export const CURRENCIES: CurrencyInfo[] = RAW.split('\n').map((line) => {
  const [code, decimals, symbol, name] = line.split('|');
  return { code, decimals: Number(decimals), symbol, name };
});

const BY_CODE = new Map(CURRENCIES.map((c) => [c.code, c]));

export const PINNED_CURRENCIES = ['INR', 'USD', 'EUR', 'GBP', 'CAD', 'AUD', 'JPY'];

export function getCurrency(code: string): CurrencyInfo {
  const c = BY_CODE.get(code.toUpperCase());
  if (!c) throw new Error(`Unknown currency ${code}`);
  return c;
}

export function isCurrency(code: string): boolean {
  return BY_CODE.has(code.toUpperCase());
}

/** Pinned first, then alphabetical; filtered by code or name. */
export function searchCurrencies(query = ''): CurrencyInfo[] {
  const q = query.trim().toLowerCase();
  const match = (c: CurrencyInfo) =>
    !q || c.code.toLowerCase().includes(q) || c.name.toLowerCase().includes(q);
  const pinned = PINNED_CURRENCIES.map((code) => BY_CODE.get(code)!).filter(match);
  const rest = CURRENCIES.filter((c) => !PINNED_CURRENCIES.includes(c.code) && match(c));
  return [...pinned, ...rest];
}
